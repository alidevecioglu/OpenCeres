#!/usr/bin/env python3
"""Generate crates/core/src/vsop87_earth.rs, a truncated VSOP87A Earth series.

Source: Bretagnon P., Francou G. (1988), "Planetary theories in rectangular and
spherical variables. VSOP87 solutions", Astron. Astrophys. 202, 309.
Data file VSOP87A.ear (CDS/VizieR catalogue VI/81, also IMCCE's ephem FTP):
heliocentric rectangular coordinates of the Earth, dynamical ecliptic and
equinox J2000, T in Julian millennia (TDB) from J2000.

Usage (from the repo root, nothing is installed):

    curl -sSfL -o .cache/vsop87/VSOP87A.ear \
        https://ftp.imcce.fr/pub/ephem/planets/vsop87/VSOP87A.ear
    curl -sSfL -o .cache/vsop87/vsop87.chk \
        https://ftp.imcce.fr/pub/ephem/planets/vsop87/vsop87.chk
    python3 -I crates/core/tools/gen_vsop87.py .cache/vsop87/VSOP87A.ear \
        .cache/vsop87/vsop87.chk > crates/core/src/vsop87_earth.rs

The script checks the full series against the published check values, then
keeps a term of degree a when A * TMAX**a >= THRESHOLD and reports the
truncation error (full vs truncated) over 2000-2050 on stderr.
"""

import math
import re
import sys

THRESHOLD = 1.0e-8  # au, at the edge of the validity window
TMAX = 0.05  # Julian millennia: J2000 +/- 50 years
SPAN = (2000.0, 2050.0)  # calendar years checked for the error report


def read_series(path):
    """series[coord][alpha] = [(A, B, C), ...]"""
    series = [[[] for _ in range(6)] for _ in range(3)]
    coord = alpha = None
    counts = {}
    with open(path) as f:
        for line in f:
            if line.startswith(" VSOP87"):
                m = re.search(r"VARIABLE (\d).*\*T\*\*(\d)\s+(\d+) TERMS", line)
                coord, alpha, count = int(m[1]) - 1, int(m[2]), int(m[3])
                counts[(coord, alpha)] = count
                continue
            if not line.strip():
                continue
            # Fortran format (1x,4i1,i5,12i3,f15.11,2f18.11,f14.11,f20.11):
            # the last three numbers are A, B, C.
            a, b, c = (float(x) for x in line.split()[-3:])
            series[coord][alpha].append((a, b, c))
    for (coord, alpha), count in counts.items():
        assert len(series[coord][alpha]) == count, f"term count mismatch {coord} {alpha}"
    return series


def evaluate(series, t):
    out = []
    for coord in series:
        total = 0.0
        for alpha, terms in enumerate(coord):
            s = sum(a * math.cos(b + c * t) for a, b, c in terms)
            total += s * t**alpha
        out.append(total)
    return out


def check_values(path):
    """(jd, [x, y, z]) for VSOP87A EARTH from vsop87.chk."""
    values = []
    with open(path) as f:
        lines = f.readlines()
    for i, line in enumerate(lines):
        m = re.match(r"\s*VSOP87A\s+EARTH\s+JD(\d+\.\d+)", line)
        if m:
            nums = re.findall(r"[xyz]\s+(-?\.?\d*\.?\d+)\s+au\b", lines[i + 1])
            values.append((float(m[1]), [float(x) for x in nums]))
    return values


def main():
    series = read_series(sys.argv[1])
    checks = check_values(sys.argv[2])
    assert checks, "no VSOP87A EARTH check values found"
    for jd, ref in checks:
        got = evaluate(series, (jd - 2451545.0) / 365250.0)
        err = max(abs(g - r) for g, r in zip(got, ref))
        assert err < 2e-10, f"full series disagrees with check value at JD {jd}: {err}"
    print(f"full series matches {len(checks)} check values to < 2e-10 au", file=sys.stderr)

    kept = [
        [[term for term in terms if term[0] * TMAX**alpha >= THRESHOLD] for alpha, terms in enumerate(coord)]
        for coord in series
    ]
    total = sum(len(t) for c in series for t in c)
    n_kept = sum(len(t) for c in kept for t in c)

    worst = 0.0
    steps = 2000
    for i in range(steps + 1):
        year = SPAN[0] + (SPAN[1] - SPAN[0]) * i / steps
        t = (year - 2000.0) / 1000.0
        full, trunc = evaluate(series, t), evaluate(kept, t)
        worst = max(worst, math.dist(full, trunc))
    arcsec = worst * 206264.806
    print(
        f"kept {n_kept} of {total} terms; max |full - truncated| over "
        f"{SPAN[0]:.0f}-{SPAN[1]:.0f}: {worst:.2e} au ({arcsec:.3f} arcsec at 1 au)",
        file=sys.stderr,
    )

    ref_jd, ref = checks[0]
    w = sys.stdout.write
    w("// Generated by crates/core/tools/gen_vsop87.py; do not edit.\n")
    w("// VSOP87A Earth (Bretagnon & Francou 1988, A&A 202, 309; CDS VI/81),\n")
    w("// heliocentric rectangular, dynamical ecliptic and equinox J2000, au.\n")
    w(f"// Terms with A * {TMAX}^alpha < {THRESHOLD:.0e} au dropped: {n_kept} of {total} kept,\n")
    w(f"// max error {worst:.1e} au ({arcsec:.3f}\") over {SPAN[0]:.0f}-{SPAN[1]:.0f}.\n\n")
    w("// Some phases happen to be close to pi; they are data, not the constant.\n")
    w("#![allow(clippy::approx_constant)]\n\n")
    w(f"/// Published check value (vsop87.chk), JD {ref_jd} TDB: x, y, z in au.\n")
    w(f"#[cfg(test)]\npub const CHECK_J2000: [f64; 3] = [{ref[0]:.10}, {ref[1]:.10}, {ref[2]:.10}];\n\n")
    late_jd = 2461317.5  # 2026-10-04, the reference field's night
    late = evaluate(series, (late_jd - 2451545.0) / 365250.0)
    w(f"/// Full (untruncated) series at JD {late_jd} TDB: x, y, z in au.\n")
    w(f"#[cfg(test)]\npub const FULL_{int(late_jd)}: [f64; 3] = [{late[0]:.12}, {late[1]:.12}, {late[2]:.12}];\n\n")
    w(f"/// Truncation error bound over {SPAN[0]:.0f}-{SPAN[1]:.0f} (au), as measured by the generator.\n")
    w(f"#[cfg(test)]\npub const MAX_ERROR: f64 = {worst:.1e};\n\n")
    w("/// `EARTH[coordinate][alpha]`: terms (A, B, C) of A·cos(B + C·T)·T^alpha.\n")
    w("#[rustfmt::skip]\n")
    w("pub const EARTH: [[&[[f64; 3]]; 6]; 3] = [\n")
    for coord in kept:
        w("    [\n")
        for terms in coord:
            w("        &[\n")
            for a, b, c in terms:
                w(f"            [{a!r}, {b!r}, {c!r}],\n")
            w("        ],\n")
        w("    ],\n")
    w("];\n")


main()
